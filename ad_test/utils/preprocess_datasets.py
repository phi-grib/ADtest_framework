import gc
import pandas as pd

from rdkit import rdBase
from typing import Tuple, Optional

from curate.chem import chemical_description
from .logger import LOG

rdBase.DisableLog('rdApp.warning')

class Preprocess(object):
    """
    Class to handle the preprocessing of series using chemical descriptors.
    Preprocess steps:
        1. Describe training and test series.
        2. Combine and clean data by removing rows with NaN values.
        3. Align training and test datasets to ensure consistency.
        4. Obtain InChI, InChIKey and ChEMBL ID from SMILES using ChEMBL web services.
        5. Retrieve all five levels of ATC codes (1-5), resolving multi-codes based on training set frequency.
    """

    def __init__(self, train_series: pd.DataFrame, test_series: pd.DataFrame, id_col: str, struct_col: str, activity_col: str,
                 descriptors: str, prediction_col: Optional[str] = None, logger: Optional[LOG] = None):
        
        if logger:
            # If a logger is provided (by main.py), use it.
            self.logger = logger
        else:
            # If no logger is provided, create a default one for interactive use.
            self.logger = LOG(name=self.__class__.__name__, log_file_path='preprocess_interactive.log')
            self.logger.info("No logger provided; created default logger for interactive session.")

        self.logger.info("Initializing Preprocessing.")

        self.train_series = train_series
        self.test_series = test_series
        self.id_col = id_col
        self.struct_col = struct_col
        self.activity_col = activity_col
        self.descriptors = descriptors
        self.prediction_col = prediction_col

        # 1. Core Metadata: Always tracked because desc_processor generates them
        #    or they are required.
        core_metadata = ['canon_smiles']

        # NEW: If a prediction column is defined in config, add it to core metadata.
        # We treat it as 'core' so it gets added to self.metadata regardless of whether 
        # it exists in the training set (since it often only exists in the test set).
        if self.prediction_col:
            core_metadata.append(self.prediction_col)

        # 2. Optional Metadata: Only tracked if they exist in the input data.
        target_optional_metadata = ['chembl_id', 'inchi', 'inchikey', 
                                    'chembl_preferred_name', 'pubchem_cid']
        
        # Check which optional columns are actually in the training data
        existing_optional_metadata = [col for col in target_optional_metadata if col in self.train_series.columns]

        # 3. Final Metadata List: Core + Existing Optional + ID Column
        #    Use set() to avoid duplicates (e.g., if canon_smiles was in input)
        self.metadata = list(set(core_metadata + existing_optional_metadata + [self.id_col]))

        # Logging (Optional)
        missing_optional = set(target_optional_metadata) - set(existing_optional_metadata)
        if missing_optional:
            self.logger.info(f"Optional metadata not found in input (will be ignored): {missing_optional}")

        # Stores the list of feature column names (descriptors or fingerprints)
        self.features = None       

    def describe_series(self, data: pd.DataFrame) -> pd.DataFrame:
        """
        Describes a given series using chemical descriptors based on the chosen
        descriptor type (e.g., 'rdkit' or 'fps').

        Args:
            data (pd.DataFrame): The DataFrame to describe.

        Returns:
            pd.DataFrame: DataFrame containing the selected descriptors or fingerprints
                          and the activity column ('Y').
        """
        desc_processor = chemical_description.Description(data, self.id_col, self.struct_col)
        
        desc_processor.add_descriptors_and_fingerprints()
    
        # DYNAMIC SELECTION:
        # We look for columns in self.metadata that exist in the GENERATED compound_dataframe.
        # Since 'canon_smiles' is generated by desc_processor, it will be found here 
        # even if it wasn't in the input 'data'.
        available_metadata = [col for col in self.metadata if col in desc_processor.compound_dataframe.columns]
        
        if self.descriptors == 'rdkit':
            features = desc_processor.descriptor_dataframe.columns[1:].tolist()
            described_data = pd.concat([desc_processor.descriptor_dataframe.iloc[:,1:], # type: ignore
                                        desc_processor.compound_dataframe[[self.activity_col] + available_metadata]], axis=1)
        elif self.descriptors == 'fps':
            features = desc_processor.morgan_dataframe.columns[1:].tolist()
            described_data = pd.concat([desc_processor.morgan_dataframe.iloc[:,1:], # type: ignore
                                        desc_processor.compound_dataframe[[self.activity_col] + available_metadata]], axis=1)
        else:
            self.logger.error("Invalid descriptor type. Choose 'rdkit' or 'fps'.")
            raise ValueError("Invalid descriptor type. Choose 'rdkit' or 'fps'.")

        return described_data, features
    
    def preprocess_and_align_data(self, data: pd.DataFrame) -> Tuple[pd.DataFrame, pd.Series, pd.Series]:
        """
        Removes any rows with NaN values from the combined features and target data.
        """
        self.logger.info(f"Data shape before cleaning: {data.shape}")

        # Determine which metadata columns are actually in this SPECIFIC dataframe
        # This handles cases where test data might lack columns that train data had,
        # or where we are processing data that includes generated columns like 'canon_smiles'.
        current_metadata = [col for col in self.metadata if col in data.columns]

        if not self.features:
            self.logger.warning("Warning: Features list is empty.")
            # Drop NaNs across all columns EXCEPT metadata
            cols_to_check = [col for col in data.columns if col not in [self.activity_col] + current_metadata]
            cleaned_df = data.dropna(subset=cols_to_check)
        else:
            cleaned_df = data.dropna(subset=self.features)
        
        # Split: Drop the metadata columns that exist in this dataframe
        cleaned_X = cleaned_df.drop([self.activity_col] + current_metadata, axis=1)
        cleaned_y = cleaned_df[self.activity_col]
        
        # Keep the metadata
        cleaned_ids = cleaned_df[current_metadata].copy()

        return cleaned_X, cleaned_y, cleaned_ids
    
    def execute_pipeline(self) -> Tuple[pd.DataFrame, pd.Series, pd.Series, pd.DataFrame, pd.Series, pd.Series]:
        """
        Orchestrates the entire preprocessing pipeline.

        Returns:
            tuple: A tuple containing the cleaned training and testing datasets.
        """
        
        self.logger.info("Starting memory-efficient preprocessing pipeline...")

        # --- Process Training Set ---
        self.logger.info("--- Processing Training Set ---")
        train_described, self.features = self.describe_series(self.train_series)
        
        X_train, y_train, train_ids = self.preprocess_and_align_data(train_described)
        
        self.logger.info(f"Final training data shape: X={X_train.shape}, y={y_train.shape}")
        
        # --- Memory Management ---
        # Explicitly delete the large intermediate dataframe to free up memory
        self.logger.info("Releasing memory from intermediate training data...")
        del train_described
        gc.collect() # Trigger garbage collection

        X_test, y_test, test_ids = None, None, None
        if self.test_series is not None:
            self.logger.info("--- Processing Test Set ---")
            test_described, _ = self.describe_series(self.test_series) # Features are already set from training data
            X_test, y_test, test_ids = self.preprocess_and_align_data(test_described)
            
            self.logger.info(f"Final testing data shape: X={X_test.shape}, y={y_test.shape}")
            
            # --- Memory Management ---
            self.logger.info("Releasing memory from intermediate test data...")
            del test_described
            gc.collect()
        
        self.logger.info("Preprocessing complete!")
        
        return X_train, y_train, train_ids, X_test, y_test, test_ids
